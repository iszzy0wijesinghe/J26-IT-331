
"""Versioned sensor feature extraction for the initial C3 simulation.

This feature schema supports the three environmental measurements
generated by GeoNex's current baseline simulator.

It is an engineering baseline, not the final physical sensor registry.
"""

from math import isfinite

from shared.contracts.telemetry import TelemetryPacket

FEATURE_SCHEMA_VERSION = "c3-simulator-features-v1"

# sensor_type -> (C3 feature name, expected telemetry unit)
SENSOR_FEATURE_SPEC: dict[str, tuple[str, str]] = {
    "SOIL_MOISTURE": ("soil_moisture_pct", "%"),
    "TEMPERATURE": ("temperature_c", "C"),
    "ATMOSPHERIC_PRESSURE": ("atmospheric_pressure_hpa", "hPa"),
}

FEATURE_NAMES: tuple[str, ...] = tuple(
    feature_name
    for feature_name, _unit in SENSOR_FEATURE_SPEC.values()
)


def extract_simulator_sensor_features(
    packet: TelemetryPacket,
) -> dict[str, float | None]:
    """Extract a stable three-feature vector from one telemetry packet.

    Rules:
    - Use normalized `value`, never substitute uncalibrated `raw_value`.
    - Keep a stable feature schema even when measurements are missing.
    - Require the expected unit for each present normalized value.
    - Reject ambiguous duplicate sensor types.
    - Reject non-finite values rather than passing NaN or infinity.
    - Ignore sensor types outside this versioned baseline schema.

    Multiple physical sensors of the same type will require a
    separately versioned, channel-aware feature schema.
    """

    features: dict[str, float | None] = {
        feature_name: None
        for feature_name in FEATURE_NAMES
    }

    seen_types: set[str] = set()

    for measurement in packet.measurements:
        specification = SENSOR_FEATURE_SPEC.get(
            measurement.sensor_type
        )

        if specification is None:
            continue

        feature_name, expected_unit = specification

        if measurement.sensor_type in seen_types:
            raise ValueError(
                "Duplicate sensor type in baseline C3 feature schema: "
                f"{measurement.sensor_type}"
            )

        seen_types.add(measurement.sensor_type)

        # An uncalibrated/raw-only measurement is missing from
        # the normalized C3 input, even if raw_value is present.
        if measurement.value is None:
            continue

        if measurement.unit != expected_unit:
            raise ValueError(
                f"Unexpected unit for {measurement.sensor_type}: "
                f"expected {expected_unit!r}, "
                f"received {measurement.unit!r}"
            )

        numeric_value = float(measurement.value)

        if not isfinite(numeric_value):
            raise ValueError(
                f"Non-finite C3 measurement: {measurement.sensor_type}"
            )

        features[feature_name] = numeric_value

    return features
