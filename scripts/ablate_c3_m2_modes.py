"""Compare GeoNex C3 gradient boosting with and without mode features."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from scripts.ablate_c3_m1_modes import select_columns
from scripts.train_c3_m1_ridge import HORIZONS, prepare_data
from scripts.train_c3_m2_gradient_boosting import train_horizon


def main():
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--dataset-dir",
        type=Path,
        default=Path("data/processed/c3_v2"),
    )

    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("data/processed/c3_m2_ablation"),
    )

    args = parser.parse_args()

    manifest = json.loads(
        (args.dataset_dir / "manifest.json").read_text(
            encoding="utf-8"
        )
    )

    if manifest["export_version"] != "c3-fixed-horizon-v2":
        raise ValueError("Unsupported dataset version")

    print("Extracting C3 tabular features...")

    prepared, feature_names = prepare_data(args.dataset_dir)

    if len(feature_names) != 79:
        raise ValueError(
            f"Expected 79 features, found {len(feature_names)}"
        )

    results = {}

    for horizon in HORIZONS:
        print(f"\n=== {horizon}-MINUTE M2 MODE ABLATION ===")

        X_train, y_train = prepared[("train", horizon)]
        X_val, y_val = prepared[("validation", horizon)]

        horizon_results = {}

        for configuration in ("WITHOUT_MODE", "WITH_MODE"):
            columns = select_columns(
                feature_names,
                configuration,
            )

            print(
                f"\nConfiguration: {configuration} "
                f"({len(columns)} features)"
            )

            best = train_horizon(
                X_train[:, columns],
                y_train,
                X_val[:, columns],
                y_val,
            )

            horizon_results[configuration] = {
                "feature_count": len(columns),
                "selected_parameters": best["parameters"],
                "validation": best["validation"],
            }

            print(
                f"Selected validation MAE: "
                f"{best['validation']['mae']:.4f}"
            )

        without_mae = horizon_results[
            "WITHOUT_MODE"
        ]["validation"]["mae"]

        with_mae = horizon_results[
            "WITH_MODE"
        ]["validation"]["mae"]

        improvement = (
            (without_mae - with_mae) / without_mae * 100.0
            if without_mae > 0
            else 0.0
        )

        horizon_results["mode_mae_improvement_pct"] = improvement

        results[str(horizon)] = horizon_results

        print(
            f"\nMode MAE improvement: {improvement:+.2f}%"
        )

    report = {
        "experiment": "C3_M2_OPERATING_MODE_ABLATION",
        "dataset_version": manifest["export_version"],
        "source_origin": "SIMULATED",
        "selection_metric": "VALIDATION_MAE",
        "results": results,
        "limitations": [
            "Synthetic telemetry only",
            "No verified landslide-event ground truth",
            "Operating modes are generated by a synthetic controller",
            "Timing features remain in both configurations",
            "No EMERGENCY forecast-origin coverage",
            "Overlapping examples are not independent",
            "Validation results are exploratory",
        ],
    }

    args.output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    report_path = args.output_dir / "metrics.json"

    report_path.write_text(
        json.dumps(report, indent=2) + "\n",
        encoding="utf-8",
    )

    print("\n=== M2 MODE ABLATION COMPLETED ===")
    print(f"Saved results: {report_path}")


if __name__ == "__main__":
    main()